"""
The data shapes used everywhere else in the project.

Only two ideas live here:

  FiscalYear        - the seven raw numbers for a single financial year
  FinancialHistory  - several FiscalYears for one company, plus provenance

Keeping these in one small file means every other module agrees on what a
"year of financials" looks like, and nothing has to guess about field names.

IMPORTANT RULE OF THIS PROJECT: a number we could not obtain is None.
It is never zero, and it is never estimated. Zero and "unknown" mean very
different things in credit analysis -- zero debt is excellent news, unknown
debt means we cannot form a view at all.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional

# Every monetary field below is in the same units (see FinancialHistory.units),
# normally millions of the reporting currency.


@dataclass
class FiscalYear:
    """One fiscal year of raw financial data, straight from the source.

    No ratios here on purpose. This holds only reported inputs, so you can
    always trace a ratio back to the numbers that produced it.
    """

    year: int

    # --- Income statement ---------------------------------------------------
    revenue: Optional[float] = None
    # Total sales for the year. The "top line".

    ebitda: Optional[float] = None
    # Earnings Before Interest, Taxes, Depreciation & Amortization.
    # A rough proxy for cash generated by the core business before any
    # financing decisions. See README for the full explanation.

    interest_expense: Optional[float] = None
    # Cash cost of carrying the debt for the year. Stored as a POSITIVE
    # number meaning "money paid out", even though some data sources report
    # it as a negative. data_loader normalises the sign.

    # --- Balance sheet ------------------------------------------------------
    cash: Optional[float] = None
    # Cash and cash equivalents at the year-end date. A point-in-time
    # snapshot, unlike revenue/EBITDA which cover the whole year.

    total_debt: Optional[float] = None
    # All borrowings: short-term debt + long-term debt. This is debt in the
    # financing sense -- it does NOT include accounts payable or other
    # ordinary operating liabilities.

    # --- Cash flow statement ------------------------------------------------
    operating_cash_flow: Optional[float] = None
    # Cash actually generated by operations. Unlike EBITDA this is a real
    # cash number and includes working capital swings and cash interest/tax.

    capex: Optional[float] = None
    # Capital expenditure: cash spent on property, plant and equipment.
    # Stored as a POSITIVE number meaning "money spent". Most data sources
    # report capex as negative; data_loader flips the sign so the formula
    # FCF = OCF - capex reads the way the textbook writes it.

    # --- Balance sheet, extended set -------------------------------------
    # Not used by the six core credit metrics. These exist for the Altman
    # Z''-score (screener/altman.py), which measures the whole balance sheet
    # rather than debt service. All optional: a source that cannot supply them
    # leaves the Z-score unavailable rather than wrong.
    total_assets: Optional[float] = None
    current_assets: Optional[float] = None
    current_liabilities: Optional[float] = None
    retained_earnings: Optional[float] = None
    # Cumulative profit kept in the business since founding. Negative means
    # lifetime losses exceed lifetime profits, which is why Altman weights it.
    total_liabilities: Optional[float] = None
    shareholders_equity: Optional[float] = None
    operating_income: Optional[float] = None
    # EBIT. Distinct from EBITDA: depreciation and amortization are NOT added
    # back, so it is the stricter measure Altman's formula calls for.

    def missing_fields(self) -> List[str]:
        """Names of the fields we have no value for. Used by the report so
        the reader can see exactly what the analysis is blind to."""
        return [
            name
            for name in (
                "revenue",
                "ebitda",
                "interest_expense",
                "cash",
                "total_debt",
                "operating_cash_flow",
                "capex",
            )
            if getattr(self, name) is None
        ]


@dataclass
class MaturitySchedule:
    """When the debt actually comes due, as of one balance-sheet date.

    This answers the question leverage cannot: a company fails when it misses
    a payment on a date, not when a ratio crosses a threshold. High leverage
    with nothing due for five years is survivable; the same leverage with a
    large maturity next year is urgent.

    Only SEC EDGAR supplies this -- the figures come from the long-term debt
    note of the 10-K. `buckets` is ordered near to far, and any bucket the
    filing did not tag is None rather than zero.
    """

    as_of_year: int
    buckets: List["MaturityBucket"] = field(default_factory=list)
    tags_used: List[str] = field(default_factory=list)

    @property
    def total(self) -> Optional[float]:
        known = [b.amount for b in self.buckets if b.amount is not None]
        return sum(known) if known else None

    @property
    def due_within_one_year(self) -> Optional[float]:
        return self.buckets[0].amount if self.buckets else None


@dataclass
class MaturityBucket:
    """One rung of the maturity ladder."""

    label: str
    amount: Optional[float]


@dataclass
class FinancialHistory:
    """Several years of data for one company, newest-last.

    `provenance` is a free-text note recording where the numbers came from.
    It is printed in the report. This is deliberate: a screening tool that
    cannot tell you the origin of its inputs is not a usable analytical tool.
    """

    ticker: str
    company_name: str
    years: List[FiscalYear] = field(default_factory=list)
    currency: str = "USD"
    units: str = "millions"
    source: str = "unknown"
    sector: Optional[str] = None
    industry: Optional[str] = None
    # Industry is descriptive only in Version 1 -- it is displayed, not used in
    # any calculation. It is carried here because peer comparison (peers.py)
    # will need it to group companies, and because "5x leverage" means
    # different things for an airline and a software company.
    provenance: str = ""
    maturities: Optional["MaturitySchedule"] = None
    # When the debt comes due. Only EDGAR provides this; other sources leave
    # it None and the interface says so rather than inventing a schedule.
    notes: Dict[str, str] = field(default_factory=dict)
    # notes maps a field name -> explanation, e.g.
    #   {"ebitda": "Not reported directly; computed as Operating Income + D&A"}

    @property
    def short_name(self) -> str:
        """Company name without any trailing parenthetical, for use in prose.

        Data sources append all sorts of things to the legal name, and the
        teaching files here carry a long "(SYNTHETIC...)" marker. Sentences read
        badly with that inline, so prose uses this and headers use the full name.
        """
        name = self.company_name.split("(")[0].strip()
        return name or self.company_name

    def sorted_years(self) -> List[FiscalYear]:
        """Years oldest-first, which is the order every trend check assumes."""
        return sorted(self.years, key=lambda y: y.year)

    def latest(self) -> Optional[FiscalYear]:
        """Most recent fiscal year, or None if we have no data at all."""
        years = self.sorted_years()
        return years[-1] if years else None

    def earliest(self) -> Optional[FiscalYear]:
        years = self.sorted_years()
        return years[0] if years else None
